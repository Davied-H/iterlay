export function translateCreative(text: string, language: SiteLanguage): string {
  if (language === 'zh') return text
  const key = text.trim()
  return creativeCopy[key] ? text.replace(key, creativeCopy[key]) : text
}

export function localizeCreative<T>(value: T, language: SiteLanguage): T {
  if (typeof value === 'string') return translateCreative(value, language) as T
  if (Array.isArray(value)) return value.map(item => localizeCreative(item, language)) as T
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, localizeCreative(item, language)])) as T
  return value
}
